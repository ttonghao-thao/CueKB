"""Checksummed, transactional expansion migrations, also used for empty installs."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from importlib.resources import files

from sqlalchemy import create_engine, inspect, text

LEDGER_SQL = """CREATE TABLE IF NOT EXISTS schema_revisions (
 revision text PRIMARY KEY, checksum char(64) NOT NULL, applied_at timestamptz NOT NULL DEFAULT now())"""


def migrations():
    root = files(__package__)
    return [
        (p.name.split("_", 1)[0], p.read_text())
        for p in sorted(root.iterdir(), key=lambda p: p.name)
        if p.name.endswith(".sql")
    ]


def checksum(sql):
    return hashlib.sha256(sql.encode()).hexdigest()


def render_schema():
    result = ["-- Generated by cuekb.migrations; do not edit.\nBEGIN;", LEDGER_SQL + ";"]
    for revision, sql in migrations():
        result += [
            sql,
            f"INSERT INTO schema_revisions(revision,checksum) VALUES ('{revision}','{checksum(sql)}');",
        ]
    return "\n".join(result) + "\nCOMMIT;\n"


def check_connection(conn):
    expected = {r: checksum(s) for r, s in migrations()}
    if not inspect(conn).has_table("schema_revisions"):
        raise RuntimeError("schema_upgrade_required")
    actual = dict(conn.execute(text("SELECT revision,checksum FROM schema_revisions")).all())
    if actual != expected:
        raise RuntimeError("schema_upgrade_required")
    return {"revision": max(actual), "checksums": actual}


def _adopt_baseline(conn, baseline):
    # Support only the complete pre-S1 baseline, not an arbitrary historical DB.
    inspector = inspect(conn)
    tables = {
        name: body
        for name, body in re.findall(r"CREATE TABLE (\w+) \((.*?)\n\);", baseline, re.DOTALL)
    }
    if not tables:
        raise RuntimeError("baseline_manifest_empty")
    for name, body in tables.items():
        if not inspector.has_table(name):
            raise RuntimeError("unsupported_legacy_schema")
        required = {
            line.strip().split()[0]
            for line in body.splitlines()
            if re.match(
                r"^\s{2}[a-z_]+\s+(?:uuid|text|bigint|integer|boolean|timestamptz|jsonb|char\(|bytea|document_version_status|job_status|grant_role)",
                line,
            )
        }
        columns = {c["name"] for c in inspector.get_columns(name)}
        if not required <= columns:
            raise RuntimeError("unsupported_legacy_schema")

    type_names = {
        "bigint": "int8",
        "integer": "int4",
        "boolean": "bool",
        "timestamptz": "timestamptz",
        "char": "bpchar",
    }
    for name, body in tables.items():
        actual = {
            r["column_name"]: r
            for r in conn.execute(
                text(
                    "SELECT column_name,udt_name,character_maximum_length FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=:t"
                ),
                {"t": name},
            ).mappings()
        }
        for column, type_name, length in re.findall(
            r"^  ([a-z_]+) (uuid|text|bigint|integer|boolean|timestamptz|jsonb|char|bytea|document_version_status|job_status|grant_role)(?:\((\d+)\))?",
            body,
            re.MULTILINE,
        ):
            row = actual.get(column)
            if (
                row is None
                or row["udt_name"] != type_names.get(type_name, type_name)
                or (length and row["character_maximum_length"] != int(length))
            ):
                raise RuntimeError("unsupported_legacy_schema")
    expected_indexes = set(re.findall(r"CREATE (?:UNIQUE )?INDEX (\w+)", baseline))
    actual_indexes = set(
        conn.execute(
            text("SELECT indexname FROM pg_indexes WHERE schemaname=current_schema()")
        ).scalars()
    )
    if not expected_indexes <= actual_indexes:
        raise RuntimeError("unsupported_legacy_schema")
    for name, body in re.findall(r"CREATE TYPE (\w+) AS ENUM \((.*?)\);", baseline, re.DOTALL):
        expected = re.findall(r"'([^']+)'", body)
        actual = list(
            conn.execute(
                text(
                    "SELECT e.enumlabel FROM pg_enum e JOIN pg_type t ON t.oid=e.enumtypid JOIN pg_namespace n ON n.oid=t.typnamespace WHERE n.nspname=current_schema() AND t.typname=:t ORDER BY e.enumsortorder"
                ),
                {"t": name},
            ).scalars()
        )
        if actual != expected:
            raise RuntimeError("unsupported_legacy_schema")


def upgrade(engine):
    with engine.begin() as conn:
        conn.execute(text("SET LOCAL lock_timeout='5s'"))
        conn.execute(text("SELECT pg_advisory_xact_lock(1129663301)"))
        steps = migrations()
        existing = inspect(conn).has_table("documents")
        if not inspect(conn).has_table("schema_revisions"):
            if existing:
                _adopt_baseline(conn, steps[0][1])
            conn.exec_driver_sql(LEDGER_SQL)
            if existing:
                conn.execute(
                    text("INSERT INTO schema_revisions(revision,checksum) VALUES (:r,:c)"),
                    {"r": steps[0][0], "c": checksum(steps[0][1])},
                )
        actual = dict(conn.execute(text("SELECT revision,checksum FROM schema_revisions")).all())
        if any(r not in dict(steps) or checksum(dict(steps)[r]) != c for r, c in actual.items()):
            raise RuntimeError("schema_checksum_mismatch")
        for revision, sql in steps:
            if revision not in actual:
                if (
                    revision != "0001"
                    and conn.execute(
                        text(
                            "SELECT count(*) FROM ingestion_jobs WHERE status IN ('queued','running')"
                        )
                    ).scalar()
                ):
                    raise RuntimeError("schema_upgrade_requires_drained_ingestion_jobs")
                conn.exec_driver_sql(sql)
                conn.execute(
                    text("INSERT INTO schema_revisions(revision,checksum) VALUES (:r,:c)"),
                    {"r": revision, "c": checksum(sql)},
                )
        return check_connection(conn)


def main():
    parser = argparse.ArgumentParser(
        description="Transactional schema expansion; never deletes existing content."
    )
    parser.add_argument("operation", choices=["upgrade", "check", "rollback-check", "render"])
    args = parser.parse_args()
    if args.operation == "render":
        print(render_schema(), end="")
        return
    from cuekb.config import get_settings

    engine = create_engine(get_settings().database_url)
    try:
        if args.operation == "upgrade":
            result = upgrade(engine)
        else:
            with engine.connect() as conn:
                result = check_connection(conn)
                if args.operation == "rollback-check":
                    pending = conn.execute(
                        text(
                            "SELECT count(*) FROM ingestion_jobs WHERE status IN ('queued','running')"
                        )
                    ).scalar()
                    result.update(
                        application_rollback="pre-S1 images retain legacy tables; retain expanded schema",
                        schema_downgrade="not_required",
                        pending_jobs=pending,
                    )
                    if pending:
                        raise RuntimeError("rollback_requires_draining_ingestion_jobs")
        print(json.dumps(result, ensure_ascii=False))
    except Exception as exc:
        # DB exceptions may contain credentials or private parameter values.
        raise SystemExit(
            str(exc) if type(exc) is RuntimeError else "database_schema_operation_failed"
        ) from None
    finally:
        engine.dispose()


if __name__ == "__main__":
    main()
